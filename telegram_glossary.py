def get_topic(index: int) -> dict:
    """Тема по порядковому номеру - с переходом на начало серии после
    последней темы (index берётся по модулю len(TOPICS))."""
    return TOPICS[index % len(TOPICS)]


def generate_glossary_post(topic: dict) -> Optional[str]:
    """Возвращает готовый текст поста (с заголовком и дисклеймером),
    либо None, если генерация не удалась содержательно."""
    user_prompt = f"Тема: {topic['title']}\n\nЧто нужно раскрыть: {topic['hint']}\n\nНапиши пост на эту тему."
    body = call_groq(_SYSTEM_PROMPT, user_prompt, max_tokens=500, temperature=0.8, model=config.GROQ_MODEL_SECONDARY)

    if len(body.strip()) < 30:
        logger.warning("Пост глоссария (%s) пустой/слишком короткий (%r) - пропускаю", topic["key"], body)
        return None

    text = f"📖 {topic['title']}\n\n{body.strip()}\n\n{DISCLAIMER}"
    logger.info("Сгенерирован пост глоссария (%s): %s", topic["key"], text[:150].replace("\n", " "))
    return text


def validate_glossary_post(text: str, topic: dict) -> tuple:
    """Числа в тексте должны быть подмножеством _BASE_ALLOWED (мелкие
    числа обычной речи) плюс реальных констант темы (topic['allowed_numbers']) -
    та же логика проверки, что и в остальных форматах с фактическими
    данными, просто источник фактов другой (константы бота, не рынок)."""
    allowed = _BASE_ALLOWED | topic.get("allowed_numbers", set())

    numbers = {float(n) for n in re.findall(r"[+-]?\d+\.?\d*", text.replace(",", ""))}
    unknown = [n for n in numbers if not any(abs(n - a) < 0.05 for a in allowed)]
    if unknown:
        return False, f"В посте глоссария есть числа вне ожидаемых констант темы: {unknown}"

    if DISCLAIMER.lower() not in text.lower():
        return False, "В тексте отсутствует дисклеймер"

    cliche_ok, found = cliche_filter.check_cliches(text)
    if not cliche_ok:
        return False, f"В тексте есть шаблонные ИИ-фразы: {', '.join(found)}"

    return True, ""
