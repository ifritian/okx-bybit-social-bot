"""
audience_question_generator.py - формат "Вопрос аудитории" (Bluesky).

Просто вопрос читателям, без сигнала и без обучающего контента -
вовлечение через реципрокность (когда у человека спрашивают мнение, он
охотнее отвечает и возвращается почитать ответы других) и заодно способ
собрать идеи для будущего контента прямо из комментариев.

Публикуется ТОЛЬКО в Bluesky, раз в неделю (см.
main.try_publish_audience_question) - разговорный, "тёплый" формат,
специфичный для площадки с живыми обсуждениями в комментариях.

В отличие от hot_take_generator/mini_lesson_generator - здесь НЕТ
обращения к LLM. Вопрос - это не фактическое утверждение, которое можно
исказить или обосновать неверными числами, а голый вопрос, поэтому набор
готовых формулировок написан руками: не нужно тратить вызов Groq и не
нужна отдельная валидация (нечего проверять - фактов в тексте нет).
"""
import logging
import random
from typing import Optional

logger = logging.getLogger(__name__)

QUESTIONS = [
    "Какую монету разобрать следующей? Пишите тикер в комментах 👇",
    "Что полезнее для вас: разбор конкретных сетапов или объяснение того, как работают индикаторы?",
    "Какой таймфрейм вам ближе - быстрые внутридневные сделки или позиции на несколько дней?",
    "Что вы обычно смотрите в первую очередь перед входом в сделку - RSI, объём или уровни?",
    "Стоп-лосс ставите сразу при входе или уже по ситуации? Расскажите, как делаете вы.",
    "Что для вас страшнее - пропустить хорошую сделку или войти в убыточную?",
    "Если бы пришлось навсегда убрать один индикатор из своей торговли - какой?",
    "Как давно вы в крипте и что за это время изменилось в вашем подходе к сделкам?",
    "Какая ваша самая полезная привычка в трейдинге, до которой пришлось дойти на своих ошибках?",
]


def pick_question(last_question: Optional[str]) -> str:
    """Выбирает вопрос, отличный от последнего опубликованного - тот же
    принцип ротации, что и в остальных Bluesky-форматах (hot_take/
    mini_lesson), только храним сам текст вопроса, а не тему/тикер -
    вопросов немного и они не переиспользуются в других форматах."""
    options = QUESTIONS
    if last_question in options and len(options) > 1:
        options = [q for q in options if q != last_question]
    return random.choice(options)
