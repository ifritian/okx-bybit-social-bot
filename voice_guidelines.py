"""
voice_guidelines.py - общий словарь запретов и стилевая директива для
ВСЕХ генераторов текста в боте (13 модулей с system-промптами на момент
написания - text_generator, opinion_generator, hot_take_generator,
mini_lesson_generator, treasury_generator, article_generator,
accuracy_report_generator, loss_review_generator, index_signal_generator,
telegram_extended, telegram_glossary, rebalance_advisor, volatility_alert).

Раньше у каждого генератора был свой независимый промпт без общего
"словаря" - в результате разные форматы иногда сходились на одних и тех
же шаблонных ИИ-оборотах ("Кроме того...", "Стоит отметить...", рефлекс-
вопрос в конце поста и т.п.), из-за чего аудитория со временем считывает
паттерн и весь канал начинает читаться как бот, а не как живой автор.

Использование: STYLE_DIRECTIVE добавляется в КОНЕЦ каждого system-
промпта (после специфичных для формата инструкций) - конкретные
инструкции формата (числа, лимиты длины и т.п.) имеют приоритет и не
должны противоречить этому блоку, а сам блок - про РЕГИСТР и ритм речи,
общий для всех форматов."""

# Фразы-паттерны, которые чаще всего выдают шаблонный ИИ-текст. Не
# исчерпывающий список - ориентир для модели, а не жёсткий фильтр (для
# автоматической проверки после генерации см. cliche_filter.py).
BANNED_PHRASES: list[str] = [
    "кроме того",
    "стоит отметить",
    "важно понимать",
    "важно отметить",
    "нельзя не отметить",
    "это может показаться неожиданным, но",
    "не секрет, что",
    "как известно",
    "в заключение",
    "подводя итог",
    "таким образом",
    "безусловно",
    "несомненно",
    "в современном мире",
    "хотелось бы отметить",
    "давайте разберёмся",
    "давайте разберемся",
    "погружаемся в",
    "как говорится",
    "в двух словах",
    "на самом деле",
]

STYLE_DIRECTIVE = """
Пиши так, как реально пишет живой человек в чате, а не как справочная
статья:
- Без вступительных фраз-разгонов и без "воды" перед сутью - начинай
  сразу с содержания.
- Рваный ритм: короткая фраза, потом одна подлиннее - не выравнивай все
  предложения под одну длину и структуру.
- Конкретика вместо общих слов - если можно назвать вещь точнее, называй
  точнее (в пределах реальных данных, которые тебе даны).
- Не заканчивай текст дежурным риторическим вопросом или обобщающим
  выводом "для галочки" - заканчивай там, где мысль реально закончилась.
- НЕ используй фразы-клише вроде: "кроме того", "стоит отметить",
  "важно понимать", "важно отметить", "нельзя не отметить", "это может
  показаться неожиданным, но", "не секрет, что", "как известно",
  "в заключение", "подводя итог", "таким образом", "безусловно",
  "несомненно", "в современном мире", "давайте разберёмся", "на самом
  деле" - и вообще любые канцелярские переходы такого типа.
- Не хеджируй мысль несколькими словами подряд ("возможно, вероятно, в
  какой-то степени") - если не уверен, скажи это одним словом и иди
  дальше."""
